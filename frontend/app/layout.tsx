import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Clinical Memory AI",
  description:
    "Clinical documentation and longitudinal patient memory for physicians. " +
    "Every AI output is a draft the physician reviews, edits and attests.",
  // Patient data must never leak into a referrer header on an outbound link.
  referrer: "strict-origin-when-cross-origin",
  // This is a clinical record system; it has no business in a search index.
  robots: { index: false, follow: false },
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">{children}</body>
    </html>
  );
}
